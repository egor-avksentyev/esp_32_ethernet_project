// motor_ws.h/.cpp — постоянное WebSocket-соединение (порт 81) под удержание кнопок Up/Down
// на веб-странице (Bass/High/Volume). Отдельно от обычного /cmd (WebServer.h,
// web_control.cpp): та библиотека жёстко шлёт "Connection: close" на каждый ответ — каждый
// fetch() открывал бы новое TCP-соединение, и на Wi-Fi (особенно с телефона, из-за
// энергосбережения радио) установка соединения иногда занимает заметно дольше обычного,
// из-за чего мотор коротко замирал прямо во время удержания кнопки (см. историю в памяти
// проекта — сначала была принята за баг с очередью fetch(), тот пофиксили отдельно, а это
// осталось). Одно соединение на всё время удержания убирает эту накладную стоимость почти
// полностью — не переустанавливается на каждый тик.
//
// Протокол — предельно простой, два текстовых сообщения от клиента за весь hold:
// "up"/"down" (открыть, запускает повтор) и "stop" (или просто закрыть соединение).
// ESP32 сам, локально, шлёт CMD:U/D на Mega каждые MOTOR_WS_REPEAT_MS, не дожидаясь новых
// сообщений от клиента — так задержки сети вообще не участвуют, пока соединение открыто.
// Основная защита от "мотор не остановился" при потере соединения без штатного close —
// уже существующий SLIDER_MOTOR_IDLE_TIMEOUT на самой Mega (см. hardware_settings.h
// Mega-репозитория) — если новых CMD:U/D не будет, она остановит мотор сама, независимо от
// того, что происходит на этой стороне; здесь это НЕ дублируется намеренно.
// ============================================================================

