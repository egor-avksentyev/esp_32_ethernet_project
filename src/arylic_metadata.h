#pragma once

// ============================================================================
// arylic_metadata.h/.cpp — периодический опрос локального HTTP API Arylic-стримера
// (WiFi должен быть уже поднят). Формат ответа подтверждён на реальном устройстве
// (2026-09-10, IP 192.168.1.139): плоский JSON, без вложенности, ~370 байт:
//
//   {"type":"0",...,"status":"play",...,"Title":"4A757374204C697374656E",
//    "Artist":"41626F76652026616D703B204265796F6E64","Album":"...", ...}
//
// Title/Artist/Album — HEX-encoded строки (пары ASCII-hex-цифр = байты UTF-8), не обычный
// текст напрямую. API доступен ТОЛЬКО по HTTPS (443, самоподписанный сертификат) — обычный
// порт 80 у устройства закрыт (проверено live). Поэтому WiFiClientSecure с setInsecure(),
// не WiFiClient — это и есть главная причина, почему это ESP32-проект, а не Mega/W5500:
// у штатной библиотеки Ethernet.h на Mega вообще нет TLS, у ESP32 он есть из коробки.
// ============================================================================

#include <Arduino.h>

// Запускает опрос Arylic в отдельной FreeRTOS-задаче (на втором ядре ESP32), а не в основном
// loop() — вызывать один раз из setup(), после того как Wi-Fi поднят. Раньше опрос шёл прямо
// в loop() и блокировал веб-сервер на время TLS-запроса (HTTPClient/WiFiClientSecure —
// синхронные); при коротком ARYLIC_POLL_INTERVAL_MS это стало заметно тормозить веб-морду.
// Вся связь между этой задачей и остальным кодом (геттеры ниже, setArylicIpOverride(),
// arylicSendPlayerCommand()/arylicSetVolume() из web_control.cpp) защищена мьютексом внутри
// arylic_metadata.cpp — снаружи можно звать эти функции откуда угодно, не думая о гонках
void arylicMetadataBegin();

// true, если последний опрос реально достучался до Arylic (HTTP 200) — "система его видит"
// в терминах веб-морды (web_control.cpp): пока true, поле ручного ввода IP там неактивно,
// раз автоматика и так работает
bool arylicIsReachable();

// Текущий IP, который реально используется для запросов (резолвленный через mDNS, взятый
// из статического фолбэка, или заданный вручную) — "" если ещё ни разу не определён.
// Только для отображения на веб-странице рядом с полем ручного ввода
String arylicCurrentIp();

// Ручной ввод IP с веб-страницы (web_control.cpp, POST /arylic-ip) — принудительно
// использовать именно этот адрес вместо mDNS/статического фолбэка, пока не будет вызвано
// повторно с пустой строкой (тогда на следующем опросе снова резолвится через mDNS).
// Не сохраняется в NVS — переживает только текущую сессию питания, специально: это ручной
// костыль на случай, если автоматика не сработала, а не постоянная замена ей
void setArylicIpOverride(const char* ip);

// --- Прогресс трека для веб-страницы (web_control.cpp, GET /track) ---
// curpos/totlen у Arylic — простые строки-числа (миллисекунды), не hex, в отличие от
// Title/Artist/Album. Опрашиваются раз в ARYLIC_POLL_INTERVAL_MS, как и всё остальное —
// между опросами веб-страница сама досчитывает позицию локально по реальному прошедшему
// времени (см. arylicTrackAgeMs() ниже), чтобы полоса прогресса не "прыгала" на каждом
// опросе, а ехала плавно

bool arylicTrackIsPlaying();

// "Artist - Title" — то же, что уходит на Mega (megaLinkSendMetadata()), но отдельная копия
// специально для веб-страницы: не urезана до MEGA_LINK_META_MAX_LEN (40), там нет такого
// жёсткого ограничения экрана, как на OLED Mega
String arylicTrackText();

long arylicTrackPosMs(); // Позиция трека (мс) НА МОМЕНТ последнего успешного опроса
long arylicTrackLenMs(); // Общая длительность трека (мс)

// Сколько миллисекунд прошло с момента, когда arylicTrackPosMs() был получен — веб-страница
// прибавляет это к позиции сразу при получении, и дальше сама тикает локальным таймером
unsigned long arylicTrackAgeMs();

// Ссылка на обложку альбома — прямая ссылка на CDN сервиса-источника (например i.scdn.co
// для Spotify Connect), получена отдельным UPnP-запросом (GetPositionInfo, ARYLIC_UPNP_PORT),
// не через основной HTTPS-опрос getPlayerStatus (там обложки нет вообще). ESP32 саму картинку
// не скачивает и не хранит — веб-страница просто ставит эту ссылку в <img src>.
// "" если обложки нет — в частности AirPlay/Apple Music не отдаёт её вообще, проверено live
// (см. project_arylic_airplay_no_metadata в памяти) — не считать это багом парсинга
String arylicTrackArtUrl();

// Источник воспроизведения ("Spotify", "AirPlay", "DLNA", ...) — из "vendor" (для сервисов
// с нативной интеграцией вроде Spotify Connect) или, если он пуст, из "mode" (см.
// computeSourceName() в arylic_metadata.cpp). "" — код источника не распознан, не гадаем.
// В отличие от trackText, заполняется даже когда Title/Artist разобрать не удалось
// (типичный случай — AirPlay, см. project_arylic_airplay_no_metadata в памяти)
String arylicTrackSourceName();

// --- Управление воспроизведением (web_control.cpp, GET /playback, /volume) ---
// Работает и через AirPlay (проверено live 2026-09-12: play/pause/next/prev реально доходят
// до телефона через обратный канал AirPlay, звук физически останавливался/менялся) — хотя
// поле "status" в getPlayerStatus при этом не меняется (остаётся "play" даже когда реально
// пауза) и "curpos" не двигается вообще, пока играет AirPlay (см. project_arylic_airplay_
// no_metadata в памяти — те же поля ненадёжны и для прогресс-бара). Поэтому кнопка play/pause
// сделана через "onepause" (сама переключает состояние, не спрашивая, что сейчас) — на
// врущий "status" полагаться нельзя

// "onepause" (play/pause, переключает сам), "next", "prev" — свободный текст не принимается,
// вызывающая сторона (handlePlayback() в web_control.cpp) целиком отвечает за то, что сюда
// попадает только один из этих трёх вариантов
bool arylicSendPlayerCommand(const char* command);

// 0-100, зажимается на границах. Работает независимо от источника — это громкость самого
// усилителя Arylic, не звука на телефоне
bool arylicSetVolume(int percent);

// Последнее известное значение громкости (0-100) из getPlayerStatus, -1 — ещё не приходило
// ни разу (например Arylic пока недоступен)
int arylicCurrentVolume();

// Перемотка на абсолютную позицию (мс, переводится внутри в секунды — сама команда LinkPlay
// принимает секунды). НЕ подтверждено живьём на этом устройстве (в отличие от остального API
// в этом файле, см. README.md, "Формат ответа Arylic API") — "setPlayerCmd:seek:<сек>" это
// стандартная команда семейства LinkPlay, но именно на этом Arylic ни разу не тестировалась.
// Не работает для AirPlay (позиция для него не приходит вообще, см. arylicTrackPosMs() выше
// по файлу) — веб-страница поэтому и не показывает полосу прогресса для этого источника
bool arylicSeek(long posMs);

// Вызывать сразу после того, как arylicSendPlayerCommand("onepause") реально отправлена —
// не дожидаясь ответа опроса. Заводит (или переключает, если уже был активен) оптимистичный
// оверрайд PLAY:-состояния, которое отправляется на Mega/веб-страницу ВМЕСТО поля "status" из
// getPlayerStatus: для AirPlay это поле не меняется на паузе вообще (см.
// project_arylic_airplay_no_metadata в памяти Mega-репозитория, подтверждено live) — опрос
// сам по себе НИКОГДА не увидел бы паузу, и реле Streamer/Now Playing на Mega застревали бы
// включёнными навсегда после паузы через AirPlay.
//
// Оверрайд снимается автоматически, как только сменится источник ("mode" в ответе Arylic) —
// то есть относится только к ТЕКУЩЕМУ сеансу воспроизведения. ВАЖНАЯ ОГОВОРКА: если после
// нажатия этой кнопки воспроизведение продолжат/остановят НАПРЯМУЮ с телефона (не через
// эту кнопку), оверрайд об этом не узнает и останется в предположении с последнего
// собственного нажатия — это фундаментальное ограничение отсутствия надёжного сигнала от
// Arylic для AirPlay, а не баг данной функции
void arylicNotifyOnepausePressed();
