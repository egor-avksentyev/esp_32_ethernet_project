// wifi_provisioning.h/.cpp — режим настройки Wi-Fi: своя открытая точка доступа
// (WIFI_PROVISION_AP_SSID, config.h) + веб-страница "выбери сеть из списка + введи пароль".
// Поднимается из main.cpp ТОЛЬКО когда wifiSetupBegin() (wifi_setup.h) вернул false — то
// есть сохранённой сети нет вообще, или она не отвечает за WIFI_CONNECT_TIMEOUT_MS (типичный
// случай: устройство физически перенесли в другой дом со своей сетью).
//
// Логика в целом (см. README.md, "Провижининг Wi-Fi" за подробностями и обоснованием):
// 1. Пользователь подключает телефон к открытой точке AudioCtrl-Setup.
// 2. DNSServer отвечает на ЛЮБОЙ DNS-запрос своим же IP — это стандартный трюк
//    "captive portal": телефон сам, без участия пользователя, открывает страницу настройки
//    (тот же принцип, что у гостевых Wi-Fi в кафе/отелях), не нужно вручную вбивать IP.
// 3. На странице — список сетей поблизости (WiFi.scanNetworks()) и поле пароля.
// 4. По сохранению (wifiSaveCredentials()) — ESP.restart(). Простой и надёжный путь вместо
//    попытки на лету переключить Wi-Fi-стек из режима AP в STA без перезагрузки.
// 5. После рестарта — снова wifiSetupBegin() в main.cpp, уже с новыми credentials.
//
// Это и есть ответ на "как перебить пароль, если устройство переехало в другой дом" — новый
// ввод через эту форму ПЕРЕЗАПИСЫВАЕТ старый (wifiSaveCredentials() хранит только одну сеть,
// не список), никакого отдельного шага "сначала забыть старый" не требуется для этого случая
// (тот отдельный путь — wifiForgetCredentials(), см. web_control.h — нужен только чтобы
// СОЗНАТЕЛЬНО уйти в этот же режим, не дожидаясь физического переезда).
// ============================================================================

