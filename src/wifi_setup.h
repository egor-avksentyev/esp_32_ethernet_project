#pragma once

// ============================================================================
// wifi_setup.h/.cpp — подключение к Wi-Fi сохранённой сетью (NVS/Preferences, не зашито в
// коде — см. wifi_provisioning.h за тем, как пользователь её туда вводит) и переподключение
// при разрыве связи. Событийное (WiFi.onEvent), не поллинг — состояние "подключено" узнаём
// сразу из ARDUINO_EVENT_WIFI_STA_GOT_IP/_DISCONNECTED. При разрыве УЖЕ установленной связи —
// переподключение с нарастающей паузой (WIFI_RECONNECT_BASE_MS/_MAX_MS, config.h), сброс к
// минимуму сразу после успешного реконнекта.
//
// ЧТО ЭТОТ МОДУЛЬ НЕ ДЕЛАЕТ: не поднимает AP-режим настройки сам — если сохранённой сети нет
// вообще, или она не отвечает за WIFI_CONNECT_TIMEOUT_MS (типичный случай — устройство
// физически перенесли в другой дом/сеть), wifiSetupBegin() возвращает false, и вызывающая
// сторона (main.cpp) должна поднять wifiProvisioningBegin() вместо обычной работы.
// ============================================================================

#include <Arduino.h>

// true, если подключились сохранённой сетью в течение WIFI_CONNECT_TIMEOUT_MS.
// false — либо сохранённой сети нет вообще (первый запуск/после wifiForgetCredentials()),
// либо она не отвечает (например переезд в другой дом) — тогда main.cpp должен поднять
// wifi_provisioning.h вместо обычной работы, а не звать этот модуль второй раз
bool wifiSetupBegin();

// Вызывать из loop() каждую итерацию, пока wifiSetupBegin() вернул true — не блокирует,
// сама решает, пора ли пробовать переподключиться при разрыве УЖЕ рабочей связи
void wifiSetupMaintain();

bool wifiIsConnected();

// Сохраняет SSID/пароль в NVS, перезаписывая предыдущие значения (хранится одна сеть, не
// список) — используется wifi_provisioning.cpp после того, как пользователь ввёл новую сеть
// через форму настройки. Вступает в силу после ESP.restart() (та же логика, что и обычная
// перезагрузка после смены — не пытаемся живьём переключать Wi-Fi-стек на лету)
void wifiSaveCredentials(const char* ssid, const char* password);

// Стирает сохранённые SSID/пароль — используется endpoint'ом "забыть Wi-Fi" на обычной
// странице управления (web_control.cpp) для сознательной смены сети без физического переезда.
// После вызова следующий wifiSetupBegin() (после ESP.restart()) вернёт false — устройство
// само уйдёт в режим настройки
void wifiForgetCredentials();
